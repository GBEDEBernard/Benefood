/// Traductions de l'application (français, anglais, fon).
///
/// Les textes sources restent écrits en français dans le code : ils servent
/// de clé. `context.tr('Accueil')` renvoie la traduction correspondant à la
/// langue choisie, ou le texte français si la clé n'est pas encore traduite.
///
/// Ce choix garde le code lisible et permet de traduire progressivement,
/// écran par écran, sans jamais afficher de clé technique à l'utilisateur.
class AppLocalizations extends InheritedWidget {
  const AppLocalizations({
    super.key,
    required this.languageCode,
    required super.child,
  });

  /// Code de la langue active (`fr`, `en` ou `fon`).
  final String languageCode;

  static AppLocalizations? maybeOf(BuildContext context) =>
      context.dependOnInheritedWidgetOfExactType<AppLocalizations>();

  static AppLocalizations of(BuildContext context) {
    final localizations = maybeOf(context);
    assert(localizations != null, 'AppLocalizations absent de l’arbre.');
    return localizations!;
  }

  /// Traduit [french] dans la langue active.
  String t(String french) {
    if (languageCode == 'fr') {
      return french;
    }
    return _tables[languageCode]?[french] ?? french;
  }

  @override
  bool updateShouldNotify(AppLocalizations oldWidget) =>
      oldWidget.languageCode != languageCode;

